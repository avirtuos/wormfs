//! Metadata Protocol Module
//!
//! This module provides the protocol buffer message definitions and conversion
//! utilities for the WormFS metadata gossip protocol (Phase 2B).
//!
//! The protocol enables distributed metadata synchronization across storage nodes
//! using a master-coordinated, eventually consistent approach.

use std::path::PathBuf;
use std::time::{SystemTime, UNIX_EPOCH};
use thiserror::Error;
use uuid::Uuid;

use crate::erasure_coding::ErasureCodingConfig;
use crate::metadata_store::{
    ChunkId, ChunkMetadata, FileMetadata, StorageLocation, StripeMetadata,
};

// Include generated protobuf code
// This will be generated by tonic-build in build.rs
include!(concat!(env!("OUT_DIR"), "/wormfs.rs"));

/// Current protocol version
pub const PROTOCOL_VERSION: (u32, u32, u32) = (1, 0, 0);

/// Errors that can occur during protocol operations
#[derive(Error, Debug)]
pub enum ProtocolError {
    #[error("Invalid UUID format: {0}")]
    InvalidUuid(String),

    #[error("Invalid timestamp: {0}")]
    InvalidTimestamp(String),

    #[error("Missing required field: {0}")]
    MissingField(String),

    #[error("Protocol version mismatch: expected {expected:?}, got {got:?}")]
    VersionMismatch {
        expected: (u32, u32, u32),
        got: (u32, u32, u32),
    },

    #[error("Invalid event type: expected event payload")]
    InvalidEventType,

    #[error("Serialization error: {0}")]
    Serialization(String),
}

pub type ProtocolResult<T> = Result<T, ProtocolError>;

// ============================================================================
// Helper Functions
// ============================================================================

/// Create a protocol version message
pub fn create_protocol_version() -> ProtocolVersion {
    ProtocolVersion {
        major: PROTOCOL_VERSION.0,
        minor: PROTOCOL_VERSION.1,
        patch: PROTOCOL_VERSION.2,
    }
}

/// Validate protocol version compatibility
pub fn validate_protocol_version(version: &ProtocolVersion) -> ProtocolResult<()> {
    let got = (version.major, version.minor, version.patch);

    // Major version must match exactly
    if got.0 != PROTOCOL_VERSION.0 {
        return Err(ProtocolError::VersionMismatch {
            expected: PROTOCOL_VERSION,
            got,
        });
    }

    Ok(())
}

/// Convert SystemTime to Unix timestamp (seconds)
pub fn system_time_to_timestamp(time: SystemTime) -> u64 {
    time.duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_secs()
}

/// Convert Unix timestamp to SystemTime
pub fn timestamp_to_system_time(timestamp: u64) -> SystemTime {
    UNIX_EPOCH + std::time::Duration::from_secs(timestamp)
}

