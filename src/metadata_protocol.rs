#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    #[test]
    fn test_protocol_version() {
        let version = create_protocol_version();
        assert_eq!(version.major, 1);
        assert_eq!(version.minor, 0);
        assert_eq!(version.patch, 0);

        // Valid version should pass
        assert!(validate_protocol_version(&version).is_ok());

        // Different major version should fail
        let bad_version = ProtocolVersion {
            major: 2,
            minor: 0,
            patch: 0,
        };
        assert!(validate_protocol_version(&bad_version).is_err());
    }

    #[test]
    fn test_time_conversion() {
        let now = SystemTime::now();
        let timestamp = system_time_to_timestamp(now);
        let converted = timestamp_to_system_time(timestamp);

        // Should be very close (within 1 second due to precision loss)
        let diff = now
            .duration_since(converted)
            .unwrap_or_else(|_| converted.duration_since(now).unwrap());
        assert!(diff.as_secs() <= 1);
    }

    #[test]
    fn test_file_metadata_conversion() {
        let original = FileMetadata::new(PathBuf::from("/test/file.txt"), 1024, 0o644);

        // Convert to proto
        let proto: FileInfo = (&original).into();
        assert_eq!(proto.file_id, original.file_id.to_string());
        assert_eq!(proto.path, "/test/file.txt");
        assert_eq!(proto.size, 1024);
        assert_eq!(proto.permissions, 0o644);

        // Convert back to domain type
        let converted: FileMetadata = (&proto).try_into().unwrap();
        assert_eq!(converted.file_id, original.file_id);
        assert_eq!(converted.path, original.path);
        assert_eq!(converted.size, original.size);
        assert_eq!(converted.permissions, original.permissions);
    }

    #[test]
    fn test_storage_location_conversion() {
        let original = StorageLocation::new(
            Uuid::new_v4(),
            "disk1".to_string(),
            PathBuf::from("/storage/chunks/abc123"),
        );

        // Convert to proto
        let proto: StorageLocationInfo = (&original).into();
        assert_eq!(proto.node_id, original.node_id.to_string());
        assert_eq!(proto.disk_id, "disk1");

        // Convert back
        let converted: StorageLocation = (&proto).try_into().unwrap();
        assert_eq!(converted.node_id, original.node_id);
        assert_eq!(converted.disk_id, original.disk_id);
        assert_eq!(converted.path, original.path);
    }

    #[test]
    fn test_event_creation() {
        let file_metadata = FileMetadata::new(PathBuf::from("/test.txt"), 100, 0o644);
        let peer_id = "peer123".to_string();
        let node_id = Uuid::new_v4();

        let event = create_file_created_event(1, peer_id.clone(), node_id, &file_metadata);

        assert_eq!(event.sequence_number, 1);
        assert!(event.version.is_some());
        assert!(event.originator.is_some());

        let originator = event.originator.unwrap();
        assert_eq!(originator.peer_id, peer_id);
        assert_eq!(originator.node_id, node_id.to_string());

        // Verify event type
        match event.event {
            Some(metadata_event::Event::FileCreated(file_created)) => {
                assert!(file_created.file.is_some());
            }
            _ => panic!("Expected FileCreated event"),
        }
    }

    #[test]
    fn test_invalid_uuid_error() {
        let bad_file_info = FileInfo {
            file_id: "not-a-uuid".to_string(),
            path: "/test".to_string(),
            size: 100,
            permissions: 0o644,
            created_at: 0,
            modified_at: 0,
            accessed_at: 0,
            stripe_count: 0,
            checksum: 0,
        };

        let result: Result<FileMetadata, _> = (&bad_file_info).try_into();
        assert!(result.is_err());
        assert!(matches!(result.unwrap_err(), ProtocolError::InvalidUuid(_)));
    }
}
