/// Create a FileCreated event
pub fn create_file_created_event(
    sequence_number: u64,
    originator_peer_id: String,
    originator_node_id: Uuid,
    file_metadata: &FileMetadata,
) -> MetadataEvent {
    MetadataEvent {
        version: Some(create_protocol_version()),
        sequence_number,
        originator: Some(MetadataPeerInfo {
            peer_id: originator_peer_id,
            node_id: originator_node_id.to_string(),
            timestamp: system_time_to_timestamp(SystemTime::now()),
        }),
        timestamp: system_time_to_timestamp(SystemTime::now()),
        event: Some(metadata_event::Event::FileCreated(FileCreatedEvent {
            file: Some(file_metadata.into()),
        })),
    }
}

