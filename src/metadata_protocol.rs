/// Convert FileMetadata to FileInfo
impl From<&FileMetadata> for FileInfo {
    fn from(metadata: &FileMetadata) -> Self {
        FileInfo {
            file_id: metadata.file_id.to_string(),
            path: metadata.path.to_string_lossy().to_string(),
            size: metadata.size,
            permissions: metadata.permissions,
            created_at: system_time_to_timestamp(metadata.created_at),
            modified_at: system_time_to_timestamp(metadata.modified_at),
            accessed_at: system_time_to_timestamp(metadata.accessed_at),
            stripe_count: metadata.stripe_count,
            checksum: metadata.checksum,
        }
    }
}

/// Convert StripeMetadata to StripeInfo
impl From<&StripeMetadata> for StripeInfo {
    fn from(metadata: &StripeMetadata) -> Self {
        StripeInfo {
            file_id: metadata.file_id.to_string(),
            stripe_index: metadata.stripe_index,
            original_size: metadata.original_size as u64,
            chunk_count: metadata.chunk_count as u32,
            erasure_config: Some((&metadata.erasure_config).into()),
            created_at: system_time_to_timestamp(metadata.created_at),
        }
    }
}

/// Convert ChunkMetadata to ChunkInfo
impl From<&ChunkMetadata> for ChunkInfo {
    fn from(metadata: &ChunkMetadata) -> Self {
        ChunkInfo {
            file_id: metadata.file_id.to_string(),
            stripe_index: metadata.stripe_index,
            chunk_index: metadata.chunk_index as u32,
            size: metadata.size,
            checksum: metadata.checksum,
            storage_location: Some((&metadata.storage_location).into()),
            created_at: system_time_to_timestamp(metadata.created_at),
            last_verified: metadata.last_verified.map(system_time_to_timestamp),
        }
    }
}

/// Convert StorageLocation to StorageLocationInfo
impl From<&StorageLocation> for StorageLocationInfo {
    fn from(location: &StorageLocation) -> Self {
        StorageLocationInfo {
            node_id: location.node_id.to_string(),
            disk_id: location.disk_id.clone(),
            path: location.path.to_string_lossy().to_string(),
        }
    }
}

/// Convert ErasureCodingConfig to ErasureCodingConfigInfo
impl From<&ErasureCodingConfig> for ErasureCodingConfigInfo {
    fn from(config: &ErasureCodingConfig) -> Self {
        ErasureCodingConfigInfo {
            data_shards: config.data_shards as u32,
            parity_shards: config.parity_shards as u32,
            shard_size: config.shard_size() as u32,
        }
    }
}

