/// Convert FileInfo to FileMetadata
impl TryFrom<&FileInfo> for FileMetadata {
    type Error = ProtocolError;

    fn try_from(info: &FileInfo) -> ProtocolResult<Self> {
        let file_id = Uuid::parse_str(&info.file_id)
            .map_err(|_| ProtocolError::InvalidUuid(info.file_id.clone()))?;

        Ok(FileMetadata {
            file_id,
            path: PathBuf::from(&info.path),
            size: info.size,
            permissions: info.permissions,
            created_at: timestamp_to_system_time(info.created_at),
            modified_at: timestamp_to_system_time(info.modified_at),
            accessed_at: timestamp_to_system_time(info.accessed_at),
            stripe_count: info.stripe_count,
            checksum: info.checksum,
        })
    }
}

/// Convert StripeInfo to StripeMetadata
impl TryFrom<&StripeInfo> for StripeMetadata {
    type Error = ProtocolError;

    fn try_from(info: &StripeInfo) -> ProtocolResult<Self> {
        let file_id = Uuid::parse_str(&info.file_id)
            .map_err(|_| ProtocolError::InvalidUuid(info.file_id.clone()))?;

        let erasure_config = info
            .erasure_config
            .as_ref()
            .ok_or_else(|| ProtocolError::MissingField("erasure_config".to_string()))?;

        let erasure_config = ErasureCodingConfig::new(
            erasure_config.data_shards as usize,
            erasure_config.parity_shards as usize,
            erasure_config.shard_size as usize,
        )
        .map_err(|e| ProtocolError::Serialization(e.to_string()))?;

        Ok(StripeMetadata {
            file_id,
            stripe_index: info.stripe_index,
            original_size: info.original_size as usize,
            chunk_count: info.chunk_count as u8,
            erasure_config,
            created_at: timestamp_to_system_time(info.created_at),
        })
    }
}

/// Convert ChunkInfo to ChunkMetadata
impl TryFrom<&ChunkInfo> for ChunkMetadata {
    type Error = ProtocolError;

    fn try_from(info: &ChunkInfo) -> ProtocolResult<Self> {
        let file_id = Uuid::parse_str(&info.file_id)
            .map_err(|_| ProtocolError::InvalidUuid(info.file_id.clone()))?;

        let storage_location = info
            .storage_location
            .as_ref()
            .ok_or_else(|| ProtocolError::MissingField("storage_location".to_string()))?;

        let storage_location = storage_location.try_into()?;

        Ok(ChunkMetadata {
            file_id,
            stripe_index: info.stripe_index,
            chunk_index: info.chunk_index as u8,
            size: info.size,
            checksum: info.checksum,
            storage_location,
            created_at: timestamp_to_system_time(info.created_at),
            last_verified: info.last_verified.map(timestamp_to_system_time),
        })
    }
}

/// Convert StorageLocationInfo to StorageLocation
impl TryFrom<&StorageLocationInfo> for StorageLocation {
    type Error = ProtocolError;

    fn try_from(info: &StorageLocationInfo) -> ProtocolResult<Self> {
        let node_id = Uuid::parse_str(&info.node_id)
            .map_err(|_| ProtocolError::InvalidUuid(info.node_id.clone()))?;

        Ok(StorageLocation {
            node_id,
            disk_id: info.disk_id.clone(),
            path: PathBuf::from(&info.path),
        })
    }
}

